#include "libft.h"

char	*ft_strdup(const char *s)
{
	char		*ptr;
	size_t		len;
	size_t		i;

	i = 0;
	len = ft_strlen(s);
	ptr = malloc(sizeof(char) * (len + 1));
	if (!ptr)
		return (NULL);
	while (i < len)
	{
		ptr[i] = s[i];
		i++;
	}
	ptr[i] = '\0';
	return (ptr);
}
